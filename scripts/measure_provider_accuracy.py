"""
Measure a real model's labeling accuracy on a labeled text dataset, end to end.

This is the "high accuracy" measuring stick. It drives the running API exactly like the UI:

  1. create project + text dataset (label schema from the fixture)
  2. import a labeled CSV (text,label,split)          -> gold = origin=imported/approved
  3. run batch AI labeling through a real provider     -> proposals = origin=model/pending_review
  4. evaluate on a split                               -> accuracy vs gold, per-class P/R/F1, confusion
  5. freeze a version and export                     -> prove the result is usable

No key is needed for --provider fake. For a real model, configure a credential first
(Providers view in the UI, or POST /api/v1/provider-credentials) OR set the provider's env key
before starting the backend.

Examples:
    python scripts/measure_provider_accuracy.py --provider fake
    python scripts/measure_provider_accuracy.py --provider openai --model gpt-4o-mini
    python scripts/measure_provider_accuracy.py --provider ollama --model qwen2.5:3b
"""
from __future__ import annotations

import argparse
import json
import sys
import time
import uuid
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CSV = ROOT / "examples" / "text_intents_200.csv"
LABELS = ["billing", "technical_support", "feature_request", "general_inquiry"]


def fail(message: str, code: int = 2) -> None:
    print(f"\nABORT: {message}")
    raise SystemExit(code)


def run(args: argparse.Namespace) -> int:
    api = args.api.rstrip("/")
    fixture = Path(args.csv)
    if not fixture.exists():
        fail(f"fixture not found: {fixture} (run scripts/generate_text_fixture.py first)")

    suffix = uuid.uuid4().hex[:8]
    with httpx.Client(timeout=180.0) as client:
        # --- 0. is the API up? ------------------------------------------------
        try:
            health = client.get(f"{api}/health").json()
        except httpx.HTTPError as exc:
            fail(f"cannot reach the API at {api}: {exc}")
        print(f"API: {health.get('status')} | privacy={health.get('privacy_mode')}")

        # --- 1. provider status ----------------------------------------------
        providers = {p["name"]: p for p in client.get(f"{api}/providers").json()}
        if args.provider not in providers:
            fail(f"provider '{args.provider}' is not registered. Available: {sorted(providers)}")
        print(f"provider '{args.provider}' models: {providers[args.provider].get('models')}")

        # --- 2. project + dataset --------------------------------------------
        project = client.post(f"{api}/projects", json={
            "name": f"Accuracy measurement {suffix}",
            "description": "Generated by scripts/measure_provider_accuracy.py",
        }).json()
        dataset = client.post(f"{api}/projects/{project['id']}/datasets", json={
            "name": f"Intents {suffix}",
            "task_type": "text_classification",
            "description": f"Fixture: {fixture.name}",
            "label_schema": {"labels": LABELS},
        }).json()
        dsid = dataset["id"]
        print(f"dataset: {dsid}")

        # --- 3. import labeled CSV (gold) ------------------------------------
        with fixture.open("rb") as handle:
            imported = client.post(
                f"{api}/datasets/{dsid}/import/file",
                files={"file": (fixture.name, handle, "text/csv")},
            )
        if imported.status_code != 200:
            fail(f"import failed: HTTP {imported.status_code} {imported.text[:300]}")
        report = imported.json()
        print(f"import: accepted={report['accepted_count']} duplicates={report['duplicate_count']} "
              f"rejected={report['rejected_count']}")
        if report["rejected_count"]:
            print("  rejections:", json.dumps(report["rejected_items"][:5])[:400])
        if report["accepted_count"] == 0:
            fail("nothing imported")

        # approve gold labels so they count as ground truth (queue pages at 200 max)
        record_ids: list[str] = []
        offset = 0
        while True:
            page = client.get(f"{api}/datasets/{dsid}/queue",
                              params={"limit": 200, "offset": offset})
            if page.status_code != 200:
                fail(f"queue read failed: HTTP {page.status_code} {page.text[:300]}")
            body = page.json()
            items = body.get("items") or []
            record_ids.extend(item["id"] for item in items)
            offset += len(items)
            if not items or offset >= int(body.get("total") or 0):
                break
        bulk = client.post(f"{api}/datasets/{dsid}/review/bulk",
                           json={"record_ids": record_ids, "action": "approve",
                                 "reason": "fixture import is ground truth"})
        if bulk.status_code != 200:
            fail(f"bulk approve failed: HTTP {bulk.status_code} {bulk.text[:300]}")
        print(f"gold approved: {bulk.json()['updated']} records")

        # --- 4. real labeling run -------------------------------------------
        print(f"\nlabeling with {args.provider}:{args.model} ...")
        started = time.time()
        label_split = None if args.label_split == "all" else (args.label_split or args.split)
        print(f"  labeling scope: {'all records' if label_split is None else f'split={label_split}'}")
        run_resp = client.post(f"{api}/datasets/{dsid}/ai-annotate", json={
            "provider": args.provider,
            "model": args.model,
            "target_split": label_split,
            "only_unannotated": False,
            "limit": 500,
            "enable_consensus": args.consensus,
        })
        elapsed = time.time() - started
        if run_resp.status_code != 202:
            fail(f"ai-annotate failed: HTTP {run_resp.status_code} {run_resp.text[:400]}")
        run_body = run_resp.json()
        print(f"run {run_body['id']}: status={run_body['status']} "
              f"processed={run_body['processed_items']} failed={run_body['failed_items']} "
              f"({elapsed:.1f}s)")
        if run_body["failed_items"]:
            detail = client.get(f"{api}/runs/{run_body['id']}").json()
            for item in detail["items"][:3]:
                print(f"  item error: {item.get('error_message')}")
            if run_body["processed_items"] == 0:
                fail("every item failed — check the provider credential/key", 3)

        # --- 5. accuracy -----------------------------------------------------
        evaluation = client.post(f"{api}/datasets/{dsid}/evaluation/run",
                                 json={"split": args.split})
        if evaluation.status_code != 200:
            fail(f"evaluation failed: HTTP {evaluation.status_code} {evaluation.text[:400]}")
        metrics = evaluation.json()

        print("\n" + "=" * 72)
        print(f"ACCURACY on split '{args.split}'  (gold=approved imported, candidate=model)")
        print("=" * 72)
        print(f"  provider / model : {args.provider} / {args.model}")
        print(f"  comparable pairs : {metrics['total_samples']}")
        print(f"  gold source      : {metrics.get('gold_source')}")
        print(f"  accuracy         : {metrics['accuracy']:.4f}")
        print(f"  macro precision  : {metrics['macro_precision']:.4f}")
        print(f"  macro recall     : {metrics['macro_recall']:.4f}")
        print(f"  macro F1         : {metrics['macro_f1']:.4f}")
        print("\n  per class:")
        for name, row in (metrics.get("per_class_metrics") or {}).items():
            print(f"    {name:18} P={row['precision']:.3f} R={row['recall']:.3f} "
                  f"F1={row['f1_score']:.3f} support={row['support']}")
        print("\n  confusion matrix:")
        matrix = metrics.get("confusion_matrix") or {}
        classes = list(matrix)
        print("    true \\ pred".ljust(20) + "".join(f"{c[:12]:>14}" for c in classes))
        for true_label in classes:
            row = matrix[true_label]
            print(f"    {true_label:18}" + "".join(f"{row.get(c, 0):>14}" for c in classes))
        for warning in metrics.get("warnings") or []:
            print(f"  ! {warning}")

        # --- 6. prove the result is usable ----------------------------------
        version = client.post(f"{api}/datasets/{dsid}/versions",
                              json={"version_tag": "1.0.0"})
        if version.status_code == 200:
            vid = version.json()["id"]
            exports = {}
            for fmt in ("jsonl", "unsloth_sharegpt_vlm"):
                artifact = client.post(f"{api}/versions/{vid}/exports", json={"format": fmt})
                if artifact.status_code in (200, 201):
                    exports[fmt] = artifact.json()["sha256"][:12]
            print(f"\n  frozen version : {vid}")
            print(f"  exports        : {exports}")
        else:
            print(f"\n  freeze blocked (expected if proposals are unreviewed): "
                  f"HTTP {version.status_code}")

        print("\nreview the model's proposals in the Annotation Workspace before publishing.")
        return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--provider", default="fake", help="registered provider name (fake, openai, anthropic, ollama, ...)")
    parser.add_argument("--model", default=None, help="model id; defaults per provider")
    parser.add_argument("--csv", default=str(DEFAULT_CSV), help="labeled CSV with text,label[,split]")
    parser.add_argument("--split", default="test", help="split to evaluate (test/val/train)")
    parser.add_argument("--api", default="http://127.0.0.1:8000/api/v1")
    parser.add_argument("--label-split", default="",
                        help="only label this split (default: same as --split; 'all' labels every record)")
    parser.add_argument("--consensus", action="store_true", help="enable dual-pass verifier")
    args = parser.parse_args()

    if not args.model:
        args.model = {
            "fake": "fake-classifier-v1",
            "openai": "gpt-4o-mini",
            "anthropic": "claude-3-5-haiku-20241022",
            "ollama": "qwen2.5:3b",
        }.get(args.provider, "default-model")
    return run(args)


if __name__ == "__main__":
    sys.exit(main())
