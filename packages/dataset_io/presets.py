"""
Export Presets for Modern Training & Fine-Tuning Frameworks.
Generates tailored directory structures, configurations, and conversation formats for:
1. Unsloth (ShareGPT VLM format + train_unsloth.py)
2. Axolotl (Alpaca/ChatML format + axolotl_config.yml)
3. LLaMA-Factory (Dataset bundle + dataset_info.json registry with SHA-256)
4. Ultralytics YOLO v8/v11 (images/, labels/, classes.txt, data.yaml)
"""
from __future__ import annotations

import hashlib
import json
from typing import Any


def export_unsloth_sharegpt_vlm(manifest: dict[str, Any]) -> dict[str, bytes]:
    """
    Export dataset to Unsloth Vision-Language / ShareGPT format.
    Produces train.jsonl, val.jsonl, and an executable train_unsloth.py starter script.
    """
    records = manifest.get("records", [])
    train_lines: list[str] = []
    val_lines: list[str] = []

    for r in records:
        split = r.get("split", "train")
        payload = r.get("annotation", {}).get("payload", {})
        assets = r.get("assets", [])

        # Extract text content
        user_prompt = payload.get("text") or payload.get("instruction") or payload.get("prompt") or ""
        gpt_response = payload.get("label") or payload.get("response") or payload.get("output") or ""

        # Check for image asset
        has_image = any(a.get("role") in {"primary_image", "image"} for a in assets)
        primary_asset = assets[0] if assets else None
        image_ref = primary_asset.get("storage_key") if primary_asset and has_image else None

        conversations = []
        user_message: dict[str, Any] = {"from": "human"}
        if image_ref:
            user_message["value"] = f"<image>\n{user_prompt}" if user_prompt else "<image>\nDescribe this image."
        else:
            user_message["value"] = user_prompt or "Provide analysis for the input."
        conversations.append(user_message)

        conversations.append({
            "from": "gpt",
            "value": str(gpt_response) if gpt_response else "Approved label.",
        })

        entry: dict[str, Any] = {
            "id": r.get("record_id", ""),
            "conversations": conversations,
        }
        if image_ref:
            entry["images"] = [image_ref]

        json_line = json.dumps(entry, ensure_ascii=False)
        if split in {"val", "validation", "test"}:
            val_lines.append(json_line)
        else:
            train_lines.append(json_line)

    train_data = ("\n".join(train_lines) + "\n").encode("utf-8")
    val_data = ("\n".join(val_lines) + "\n").encode("utf-8") if val_lines else train_data

    # Executable Unsloth fine-tuning template
    dataset_name = manifest.get("dataset_name", "dataset")
    script = f'''"""
Ready-to-run Unsloth Fine-Tuning Script.
Generated by AI Dataset Engineering Platform.
"""
from unsloth import FastLanguageModel
import torch
from datasets import load_dataset
from trl import SFTTrainer
from transformers import TrainingArguments

max_seq_length = 2048
dtype = None # Auto detection
load_in_4bit = True

model, tokenizer = FastLanguageModel.from_pretrained(
    model_name="unsloth/Qwen2.5-Coder-7B-Instruct-bnb-4bit",
    max_seq_length=max_seq_length,
    dtype=dtype,
    load_in_4bit=load_in_4bit,
)

model = FastLanguageModel.get_peft_model(
    model,
    r=16,
    target_modules=["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"],
    lora_alpha=16,
    lora_dropout=0,
    bias="none",
    use_gradient_checkpointing="unsloth",
    random_state=3407,
)

dataset = load_dataset("json", data_files={{"train": "train.jsonl", "validation": "val.jsonl"}})

trainer = SFTTrainer(
    model=model,
    tokenizer=tokenizer,
    train_dataset=dataset["train"],
    eval_dataset=dataset["validation"],
    dataset_text_field="conversations",
    max_seq_length=max_seq_length,
    dataset_num_proc=2,
    packing=False,
    args=TrainingArguments(
        per_device_train_batch_size=2,
        gradient_accumulation_steps=4,
        warmup_steps=5,
        max_steps=60,
        learning_rate=2e-4,
        fp16=not torch.cuda.is_bf16_supported(),
        bf16=torch.cuda.is_bf16_supported(),
        logging_steps=1,
        optim="adamw_8bit",
        weight_decay=0.01,
        lr_scheduler_type="linear",
        seed=3407,
        output_dir="outputs_{dataset_name}",
    ),
)

trainer.train()
model.save_pretrained_merged("finetuned_{dataset_name}_lora", tokenizer, save_method="merged_16bit")
print("Training completed successfully.")
'''.encode()

    return {
        "train.jsonl": train_data,
        "val.jsonl": val_data,
        "train_unsloth.py": script,
    }


def export_axolotl_alpaca_chatml(manifest: dict[str, Any]) -> dict[str, bytes]:
    """
    Export dataset for Axolotl fine-tuning framework (Alpaca / ChatML schema + axolotl_config.yml).
    """
    records = manifest.get("records", [])
    data_records: list[dict[str, Any]] = []

    for r in records:
        payload = r.get("annotation", {}).get("payload", {})
        instruction = payload.get("text") or payload.get("instruction") or "Classify this sample."
        output = payload.get("label") or payload.get("output") or "positive"
        input_data = payload.get("input") or ""

        data_records.append({
            "instruction": instruction,
            "input": input_data,
            "output": str(output),
        })

    jsonl_bytes = ("\n".join(json.dumps(dr, ensure_ascii=False) for dr in data_records) + "\n").encode("utf-8")

    dataset_name = manifest.get("dataset_name", "dataset")
    axolotl_yaml = f"""# Axolotl Fine-Tuning Configuration
# Auto-generated by AI Dataset Engineering Platform
base_model: meta-llama/Meta-Llama-3-8B-Instruct
model_type: LlamaForCausalLM
tokenizer_type: AutoTokenizer

load_in_8bit: false
load_in_4bit: true
strict: false

datasets:
  - path: dataset.jsonl
    type: alpaca
    shards: 1

dataset_prepared_path: last_run_prepared
val_set_size: 0.1
output_dir: ./outputs_{dataset_name}

adapter: lora
lora_r: 16
lora_alpha: 32
lora_dropout: 0.05
lora_target_linear: true

sequence_len: 4096
sample_packing: true
pad_to_sequence_len: true

gradient_accumulation_steps: 4
micro_batch_size: 2
num_epochs: 3
optimizer: paged_adamw_8bit
lr_scheduler: cosine
learning_rate: 0.0002

train_on_inputs: false
group_by_length: false
bf16: auto
fp16: false
tf32: false

gradient_checkpointing: true
logging_steps: 1
flash_attention: true

warmup_steps: 10
eval_steps: 50
save_steps: 100
""".encode()

    return {
        "dataset.jsonl": jsonl_bytes,
        "axolotl_config.yml": axolotl_yaml,
    }


def export_llama_factory_bundle(manifest: dict[str, Any]) -> dict[str, bytes]:
    """
    Export dataset for LLaMA-Factory with dataset_info.json registry and SHA-256 verification.
    """
    records = manifest.get("records", [])
    formatted: list[dict[str, Any]] = []

    for r in records:
        payload = r.get("annotation", {}).get("payload", {})
        instruction = payload.get("text") or payload.get("instruction") or "Sample instruction"
        response = payload.get("label") or payload.get("output") or "Target answer"

        formatted.append({
            "instruction": instruction,
            "input": payload.get("input", ""),
            "output": str(response),
            "history": [],
        })

    json_content = json.dumps(formatted, indent=2, ensure_ascii=False).encode("utf-8")
    sha256_hash = hashlib.sha256(json_content).hexdigest()

    dataset_key = manifest.get("dataset_name", "custom_dataset").lower().replace(" ", "_")
    dataset_info = {
        dataset_key: {
            "file_name": f"{dataset_key}.json",
            "file_sha256": sha256_hash,
            "columns": {
                "prompt": "instruction",
                "query": "input",
                "response": "output",
                "history": "history",
            },
        }
    }
    info_bytes = json.dumps(dataset_info, indent=2, ensure_ascii=False).encode("utf-8")

    return {
        f"{dataset_key}.json": json_content,
        "dataset_info.json": info_bytes,
    }


def export_ultralytics_yolo(manifest: dict[str, Any]) -> dict[str, bytes]:
    """
    Export dataset for Ultralytics YOLO (v8 / v9 / v10 / v11).
    Produces images/, labels/, classes.txt, and canonical data.yaml.
    """
    records = manifest.get("records", [])
    label_schema = manifest.get("label_schema", {})
    classes: list[str] = label_schema.get("classes") or label_schema.get("labels") or []

    # Collect unique classes from annotations if not explicitly in schema
    class_set: set[str] = set(classes)
    for r in records:
        payload = r.get("annotation", {}).get("payload", {})
        for b in payload.get("boxes", []):
            if "label" in b:
                class_set.add(b["label"])
    final_classes = sorted(class_set) if class_set else ["object"]
    class_to_idx = {cls_name: i for i, cls_name in enumerate(final_classes)}

    files: dict[str, bytes] = {}
    files["classes.txt"] = ("\n".join(final_classes) + "\n").encode("utf-8")

    for r in records:
        split = r.get("split", "train")
        rec_id = r.get("record_id", "rec")
        payload = r.get("annotation", {}).get("payload", {})
        boxes = payload.get("boxes", [])

        # Label lines: <class_idx> <x_center> <y_center> <width> <height>
        yolo_lines: list[str] = []
        for box in boxes:
            cls_name = box.get("label", final_classes[0])
            c_idx = class_to_idx.get(cls_name, 0)

            x = float(box.get("x", 0.0))
            y = float(box.get("y", 0.0))
            w = float(box.get("w", box.get("width", 0.1)))
            h = float(box.get("h", box.get("height", 0.1)))

            # If pixel coordinates, normalize assuming standard display bounds if needed
            if x > 1.0 or y > 1.0 or w > 1.0 or h > 1.0:
                # Treat as normalized if already in 0-1, otherwise normalize by 1000
                x = min(1.0, max(0.0, x / 1000.0))
                y = min(1.0, max(0.0, y / 1000.0))
                w = min(1.0, max(0.001, w / 1000.0))
                h = min(1.0, max(0.001, h / 1000.0))

            x_center = min(1.0, max(0.0, x + (w / 2.0)))
            y_center = min(1.0, max(0.0, y + (h / 2.0)))
            yolo_lines.append(f"{c_idx} {x_center:.6f} {y_center:.6f} {w:.6f} {h:.6f}")

        label_content = ("\n".join(yolo_lines) + "\n").encode("utf-8")
        files[f"labels/{split}/{rec_id}.txt"] = label_content

    # data.yaml
    names_dict = {i: name for i, name in enumerate(final_classes)}
    data_yaml = """# Ultralytics YOLO Dataset Configuration
# Auto-generated by AI Dataset Engineering Platform
path: ./
train: images/train
val: images/val
test: images/test

names:
"""
    for idx, name in names_dict.items():
        data_yaml += f"  {idx}: {name}\n"

    files["data.yaml"] = data_yaml.encode("utf-8")
    return files
